#!/usr/bin/env node
// Set up (or refresh) a wireframe folder for site-layout: wire.css, wire.js, theme.css from a theme
// JSON, and a starting page if there is none yet. Re-run it after changing the theme or the grid.
//
// Usage (from anywhere; the kit is found from this script's real location):
//   node ~/.claude/skills/site-layout/scripts/wire.mjs <dir> [--theme concept/theme.json | --kit-theme graphite]
//        [--site "Site name"] [--cols 12 --gutter 24 --margin 20 --cols-m 4 --gutter-m 12 --margin-m 16]
// Open <dir>/index.html straight from disk. Every other page in <dir> links the same three files.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const HERE = path.dirname(fs.realpathSync(fileURLToPath(import.meta.url)))
const KIT = process.env.CREATIVE_KIT ? path.resolve(process.env.CREATIVE_KIT) : path.resolve(HERE, '../../..')
const { themeVars, googleFontsUrl } = await import(pathToFileURL(path.join(KIT, 'themes/theme.mjs')).href)

const args = process.argv.slice(2)
const flag = (name, fallback) => {
  const i = args.indexOf(`--${name}`)
  return i >= 0 && args[i + 1] && !args[i + 1].startsWith('--') ? args[i + 1] : fallback
}
const dir = args.find((a, i) => !a.startsWith('--') && !args[i - 1]?.startsWith('--'))
if (!dir) {
  console.error('Usage: wire.mjs <dir> [--theme theme.json | --kit-theme graphite] [--site "Name"] [--cols 12 …]')
  process.exit(1)
}

const themeFile = flag('theme', null) ? path.resolve(flag('theme')) : path.join(KIT, 'themes', `${flag('kit-theme', 'graphite')}.json`)
if (!fs.existsSync(themeFile)) {
  console.error(`No theme at ${themeFile}`)
  process.exit(1)
}
const theme = JSON.parse(fs.readFileSync(themeFile, 'utf8'))
const px = (name, fallback) => `${parseFloat(flag(name, fallback))}px`

const fonts = googleFontsUrl(theme)
const vars = Object.entries(themeVars(theme)).map(([k, v]) => `  ${k}: ${v};`)
const css = [
  `/* ${theme.name}: generated by site-layout/wire.mjs from ${path.relative(process.cwd(), themeFile)}. Re-run it rather than editing. */`,
  fonts ? `@import url('${fonts}');` : '',
  ':root {',
  ...vars,
  `  --cols: ${parseInt(flag('cols', 12))};`,
  `  --gutter: ${px('gutter', 24)};`,
  `  --margin: ${px('margin', 20)};`,
  `  --cols-m: ${parseInt(flag('cols-m', 4))};`,
  `  --gutter-m: ${px('gutter-m', 12)};`,
  `  --margin-m: ${px('margin-m', 16)};`,
  '}',
  '',
].filter(Boolean)

const out = path.resolve(dir)
fs.mkdirSync(out, { recursive: true })
const put = (name, text) => {
  fs.writeFileSync(path.join(out, name), text)
  console.log(`  write ${path.relative(process.cwd(), path.join(out, name))}`)
}
put('theme.css', css.join('\n'))
put('wire.css', fs.readFileSync(path.join(HERE, '../assets/wire.css'), 'utf8'))
put('wire.js', fs.readFileSync(path.join(HERE, '../assets/wire.js'), 'utf8'))
if (!fs.existsSync(path.join(out, 'index.html'))) {
  put('index.html', fs.readFileSync(path.join(HERE, '../assets/shell.html'), 'utf8').replaceAll('{{site}}', flag('site', 'Site')))
}
console.log(`\nOpen file://${path.join(out, 'index.html')}`)
